"""Writes docs/STATIONS.md from the MTA's station directory.

Source: "MTA Subway Stations" on data.ny.gov (dataset 39hk-dx4f), saved as
tools/mta_subway_stations.csv. Rerun after downloading a fresh copy:

    curl -L -o tools/mta_subway_stations.csv 'https://data.ny.gov/api/views/39hk-dx4f/rows.csv?accessType=DOWNLOAD'
    python3 tools/gen_stations.py
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BORO = {"M": "Manhattan", "Bk": "Brooklyn", "Bx": "Bronx", "Q": "Queens", "SI": "Staten Island"}

rows = list(csv.DictReader(open(os.path.join(HERE, "mta_subway_stations.csv"), newline="", encoding="utf-8")))
rows.sort(key=lambda r: (r["Stop Name"].lower(), r["Borough"], r["GTFS Stop ID"]))

out = [
    "# Station list",
    "",
    "Generated by `tools/gen_stations.py` from the MTA's station directory (data.ny.gov dataset",
    "`39hk-dx4f`). Search this page for your station (Ctrl/Cmd-F), then in the clock's web UI go to",
    "**Apps**, the gear icon next to **Subway**, and set:",
    "",
    "- **Line**: the train you take, e.g. `C`. Shuttles are `GS` (42 St), `FS` (Franklin Av) and",
    "  `H` (Rockaway Park); Staten Island Railway is `SI`.",
    "- **Station ID**: the **ID** column.",
    "- **Direction**: `N` or `S`, whichever column names the way you're going.",
    "",
    "Lines are the daytime routes; some lines also stop at a station at night or on weekends only.",
    "The clock shows whatever the live feed predicts for that line at that stop.",
    "",
    "| Station | Borough | Lines | ID | N = | S = |",
    "|---|---|---|---|---|---|",
]
for r in rows:
    n = r["North Direction Label"] or "-"
    s = r["South Direction Label"] or "-"
    out.append(f'| {r["Stop Name"]} | {BORO.get(r["Borough"], r["Borough"])} | {r["Daytime Routes"]} | '
               f'`{r["GTFS Stop ID"]}` | {n} | {s} |')
dst = os.path.join(HERE, "..", "docs", "STATIONS.md")
open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(rows), "stations ->", os.path.normpath(dst))
